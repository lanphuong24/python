## Tìm kiếm - Tra cứu điểm thí sinh theo tên

# Sử dụng file bt4.inp gồm 10 dòng, tương ứng với 10 thí sinh.
# Mỗi dòng gồm tên gọi (một từ), điểm Toán, điểm Lý và điểm Hóa,
# các giá trị cách nhau bởi khoảng trắng. Ví dụ: An 7.5 6 8
# Đọc dữ liệu từ file và cho phép người dùng nhập tên cần tìm từ bàn phím.
# Nếu tìm thấy, hiển thị trên màn hình tên, điểm Toán, điểm Lý,
# điểm Hóa và điểm trung bình của thí sinh đó.
# Điểm trung bình = (điểm Toán + điểm Lý + điểm Hóa) / 3.
# Hiển thị điểm trung bình làm tròn đến hai chữ số sau dấu phẩy.
# Nếu không tìm thấy, hiển thị thông báo "Không tìm thấy thí sinh".
# Nếu có nhiều thí sinh trùng tên, hiển thị tất cả thí sinh có tên đó.
