## Tìm kiếm tuần tự (Linear search)

# Cho n số nguyên và số x.
# In vị trí đầu tiên của x trong dãy, tính từ 1.
# Nếu không có, in -1.

# Input:
# Dòng 1: số nguyên n.
# Dòng 2: n số nguyên cách nhau bởi khoảng trắng.
# Dòng 3: số nguyên x cần tìm.
# Ví dụ:
# 6
# 4 9 2 9 7 1
# 9

# Output:
# Vị trí đầu tiên của x trong dãy (tính từ 1), hoặc -1 nếu không có.
# Ví dụ:
# 2
