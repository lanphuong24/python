## Tìm vị trí của tất cả số cần tìm

# Cho n số nguyên và số x.
# In các vị trí của x, tính từ 1, theo thứ tự tăng dần.
# Nếu không có, in -1.

# Input (file bt7.inp):
# Dòng 1: số nguyên n.
# Dòng 2: n số nguyên cách nhau bởi khoảng trắng.
# Dòng 3: số nguyên x cần tìm.
# Ví dụ:
# 8
# 6 2 6 4 1 6 9 2
# 6

# Output:
# Các vị trí của x cách nhau bởi khoảng trắng, hoặc -1 nếu không có.
# Ví dụ:
# 1 3 6
