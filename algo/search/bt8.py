## Đếm học sinh có điểm trung bình đạt điểm sàn

# Input (file bt8.inp):
# Dòng 1: số nguyên n là số học sinh.
# n dòng tiếp theo: mỗi dòng gồm tên và điểm trung bình,
# cách nhau bởi khoảng trắng.
# Dòng cuối: điểm sàn lọc.

# Output:
# Danh sách học sinh có điểm trung bình lớn hơn hoặc bằng điểm sàn lọc.
# Nếu không có học sinh thỏa mãn, in 0.
# Ví dụ:
# Phuong 9.1
# Ha 8.7
